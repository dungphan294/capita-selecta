#!/usr/bin/env python3
"""Turn a directory of web files into a C source file of flash-resident blobs.

Each file becomes a `const unsigned char[]`, which the linker places in
.rodata. Because flash is memory-mapped at XIP_BASE, the server can hand those
bytes straight to tcp_write() without TCP_WRITE_FLAG_COPY — nothing is copied
into RAM on the way out.

Files are gzipped when that comes out smaller, and served with
Content-Encoding: gzip. The ETag is a CRC32 of the *uncompressed* bytes, so it
is stable whether or not compression won.

Usage: embed_assets.py <web-dir> <out.c> <out.h>
"""

import gzip
import pathlib
import sys
import zlib

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".css":  "text/css; charset=utf-8",
    ".js":   "text/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".svg":  "image/svg+xml",
    ".ico":  "image/x-icon",
    ".png":  "image/png",
    ".webp": "image/webp",
    ".woff2": "font/woff2",
    ".txt":  "text/plain; charset=utf-8",
}

# Compressing these again only makes them bigger.
ALREADY_COMPRESSED = {".png", ".webp", ".woff2", ".ico"}


def c_ident(path: str) -> str:
    return "asset_" + "".join(c if c.isalnum() else "_" for c in path).strip("_")


def c_bytes(blob: bytes, indent: str = "    ") -> str:
    lines = []
    for i in range(0, len(blob), 16):
        chunk = blob[i:i + 16]
        lines.append(indent + ",".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2

    web_dir = pathlib.Path(sys.argv[1])
    out_c = pathlib.Path(sys.argv[2])
    out_h = pathlib.Path(sys.argv[3])

    if not web_dir.is_dir():
        print(f"embed_assets: {web_dir} is not a directory", file=sys.stderr)
        return 1

    files = sorted(p for p in web_dir.rglob("*") if p.is_file()
                   and not p.name.startswith("."))
    if not files:
        print(f"embed_assets: no files under {web_dir}", file=sys.stderr)
        return 1

    entries = []
    raw_total = out_total = 0

    for path in files:
        url = "/" + path.relative_to(web_dir).as_posix()
        raw = path.read_bytes()
        suffix = path.suffix.lower()

        ctype = CONTENT_TYPES.get(suffix, "application/octet-stream")
        etag = f"{len(raw):x}-{zlib.crc32(raw):08x}"

        gzipped = False
        blob = raw
        if suffix not in ALREADY_COMPRESSED:
            # mtime=0 keeps the output reproducible across builds.
            packed = gzip.compress(raw, compresslevel=9, mtime=0)
            if len(packed) < len(raw):
                blob = packed
                gzipped = True

        entries.append({
            "url": url,
            "ident": c_ident(url),
            "ctype": ctype,
            "etag": etag,
            "gzip": gzipped,
            "blob": blob,
            "raw_len": len(raw),
        })
        raw_total += len(raw)
        out_total += len(blob)

    # -- assets.h ----------------------------------------------------------
    out_h.write_text(f"""/* Generated by tools/embed_assets.py — do not edit. */

#ifndef ASSETS_H
#define ASSETS_H

#include <stdbool.h>
#include <stddef.h>

typedef struct {{
    const char          *path;          /* request path, e.g. "/app.css" */
    const char          *content_type;
    const char          *etag;          /* CRC32 of the uncompressed bytes */
    const unsigned char *data;          /* lives in flash, not RAM */
    size_t               len;
    bool                 gzip;          /* send Content-Encoding: gzip */
}} asset_t;

#define ASSET_COUNT {len(entries)}

extern const asset_t assets[ASSET_COUNT];

/* NULL when nothing matches that path. */
const asset_t *asset_find(const char *path);

#endif /* ASSETS_H */
""")

    # -- assets.c ----------------------------------------------------------
    parts = [
        "/* Generated by tools/embed_assets.py — do not edit.\n"
        f" *\n"
        f" * {len(entries)} file(s), {raw_total:,} bytes of source"
        f" -> {out_total:,} bytes of flash.\n"
        " */\n\n"
        '#include <string.h>\n\n#include "assets.h"\n\n'
    ]

    for e in entries:
        note = "gzip" if e["gzip"] else "stored"
        parts.append(
            f"/* {e['url']} — {e['raw_len']:,} bytes {note}"
            f" -> {len(e['blob']):,} */\n"
            f"static const unsigned char {e['ident']}[] = {{\n"
            f"{c_bytes(e['blob'])}\n}};\n\n"
        )

    parts.append(f"const asset_t assets[ASSET_COUNT] = {{\n")
    for e in entries:
        parts.append(
            f'    {{ "{e["url"]}", "{e["ctype"]}", "{e["etag"]}",\n'
            f'      {e["ident"]}, sizeof {e["ident"]}, {"true" if e["gzip"] else "false"} }},\n'
        )
    parts.append("};\n\n")

    parts.append("""const asset_t *asset_find(const char *path)
{
    for (size_t i = 0; i < ASSET_COUNT; i++)
        if (strcmp(assets[i].path, path) == 0)
            return &assets[i];
    return NULL;
}
""")

    out_c.write_text("".join(parts))

    saved = raw_total - out_total
    print(f"embed_assets: {len(entries)} file(s), {raw_total:,} B -> "
          f"{out_total:,} B in flash ({saved:,} B saved)")
    for e in entries:
        print(f"  {e['url']:<14} {e['raw_len']:>7,} B -> {len(e['blob']):>7,} B"
              f"  {'gzip' if e['gzip'] else 'stored'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
